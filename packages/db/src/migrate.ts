import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Db } from './index';

const here = dirname(fileURLToPath(import.meta.url));
const DATABASE_DIR = process.env.DATABASE_DIR ?? resolve(here, '../../../database');

interface Migration {
  name: string;
  sql: string;
}

/** O schema v0.3 é a base; arquivos em database/migrations/ são incrementos posteriores. */
function loadMigrations(): Migration[] {
  const list: Migration[] = [
    { name: '001_schema_v0.3', sql: readFileSync(join(DATABASE_DIR, 'schema_v0.3.sql'), 'utf8') },
  ];
  const dir = join(DATABASE_DIR, 'migrations');
  if (existsSync(dir)) {
    for (const file of readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()) {
      list.push({ name: file.replace(/\.sql$/, ''), sql: readFileSync(join(dir, file), 'utf8') });
    }
  }
  return list;
}

export function adaptSql(sql: string, dialect: Db['dialect']): string {
  if (dialect === 'sqlite') return sql;
  return sql.replace(/\bid(\s+)INTEGER PRIMARY KEY\b/g, 'id$1INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
}

export async function migrate(db: Db): Promise<string[]> {
  await db.exec('CREATE TABLE IF NOT EXISTS schema_migrations (name TEXT PRIMARY KEY, applied_at TEXT NOT NULL)');
  const applied = new Set((await db.all<{ name: string }>('SELECT name FROM schema_migrations')).map((r) => r.name));
  const done: string[] = [];
  for (const m of loadMigrations()) {
    if (applied.has(m.name)) continue;
    await db.tx(async (t) => {
      await t.exec(adaptSql(m.sql, db.dialect));
      await t.run('INSERT INTO schema_migrations (name, applied_at) VALUES (?, ?)', [m.name, new Date().toISOString()]);
    });
    done.push(m.name);
  }
  return done;
}
